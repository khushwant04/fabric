def web_handler(request: httpx.Request) -> httpx.Response:
    """The demo internet: one page, reached only through the pinned demo address."""
    if request.url.host != DEMO_ADDRESS or request.headers.get("host") != "fabric-demo.test":
        return httpx.Response(404, text="not found")
    if request.url.path == "/reports/q3-latency.html":
        return httpx.Response(
            200, headers={"Content-Type": "text/html; charset=utf-8"}, content=PAGE.encode()
        )
    if request.url.path == "/reports/latest":
        return httpx.Response(302, headers={"Location": "/reports/q3-latency.html"})
    return httpx.Response(404, text="not found")


async def resolver(host: str, _port: int) -> list[str]:
    if host == "fabric-demo.test":
        return [DEMO_ADDRESS]
    raise OSError(f"{host} does not resolve in the demo network")


RESULTS = [
    {
        "title": "Fabric Q3 inference latency report",
        "url": PAGE_URL,
        "content": "Gateway-measured p50/p95 latency by region for Q3.",
    },
    {
        "title": "Fabric gateway: routing and failover",
        "url": "http://fabric-demo.test/docs/routing.html",
        "content": "How the gateway picks a backend for each request.",
    },
]


class _SearxHandler(BaseHTTPRequestHandler):
    def do_GET(self) -> None:  # noqa: N802 - http.server API
        parts = urlsplit(self.path)
        query = parse_qs(parts.query)
        if parts.path != "/search" or query.get("format") != ["json"]:
            self.send_error(404)
            return
        body = json.dumps({"query": query.get("q", [""])[0], "results": RESULTS}).encode()
        self.send_response(200)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def log_message(self, *_args: object) -> None:
        return


def main() -> None:
    port = int(sys.argv[1])
    ThreadingHTTPServer(("127.0.0.1", port), _SearxHandler).serve_forever()


if __name__ == "__main__":
    main()
