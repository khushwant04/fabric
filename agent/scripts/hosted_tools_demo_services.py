import json
import sys
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import parse_qs, urlsplit

import httpx

PAGE_URL = "http://fabric-demo.test/reports/q3-latency.html"
DEMO_ADDRESS = "203.0.113.50"

