"""Local stand-ins for `make demo-hosted-tools` (no GPU, no internet). Never used in production.

* ``python hosted_tools_demo_services.py PORT`` serves a SearXNG-compatible ``/search``
  endpoint on 127.0.0.1 (a real HTTP process: the gateway calls it exactly as it would call
  a self-hosted SearXNG, which is an operator-configured, in-cluster service).
* ``web_handler`` / ``resolver`` are injected into the demo gateway's web_fetch: the test
  page lives at ``http://fabric-demo.test/`` and that name resolves to 203.0.113.50. This
  keeps the SSRF guard fully in play (the name is resolved, every address checked, the
  connection pinned to the vetted address) while needing no network: a real page on
  127.0.0.1 could not be used, because web_fetch refuses loopback by design.
"""

